"""Reproduce frozen Python 3.12 character classes from the pinned Unicode 15 UCD.

No Android/JDK/RE2 Unicode database is consulted. Supply --source to regenerate;
without it the retained generated source and complete Unicode notice are checked.
"""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
target = root / 'app/src/main/java/org/diemobile/TrackerUnicode.java'
lock_path = root / 'regex-engine/tracker-unicode-lock.json'
notice = root / 'app/src/main/assets/notices/unicode-15.0.0.txt'
source_sha = '806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73'
license_sha = 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path)
args = parser.parse_args()

if args.source:
    data = args.source.read_bytes()
    assert hashlib.sha256(data).hexdigest() == source_sha, 'Unicode 15 source checksum differs'
    groups = {'WORD': {95}, 'DIGIT': set(), 'SPACE': set()}
    pending = None
    for line in data.decode('utf-8').splitlines():
        fields = line.split(';')
        code = int(fields[0], 16)
        if fields[1].endswith(', First>'):
            pending = code
            continue
        begin = pending if fields[1].endswith(', Last>') else code
        pending = None
        if fields[2][0] in 'LN':
            groups['WORD'].update(range(begin, code + 1))
        if fields[2] == 'Nd':
            groups['DIGIT'].update(range(begin, code + 1))
        # Python str.isspace: Zs category or bidi class WS/B/S.
        if fields[2] == 'Zs' or fields[4] in ('WS', 'B', 'S'):
            groups['SPACE'].update(range(begin, code + 1))
    def ranges(values):
        runs = []
        for value in sorted(values):
            if runs and value == runs[-1][1] + 1:
                runs[-1][1] = value
            else:
                runs.append([value, value])
        return ['\\x{%X}' % begin + ('-\\x{%X}' % end if end != begin else '') for begin, end in runs]
    lines = ['// SPDX-License-Identifier: Unicode-3.0', '// Generated by scripts/tracker-unicode.py from UnicodeData 15.0.0; see the retained Unicode notice.',
             'package org.diemobile;', '', 'final class TrackerUnicode {', '    static final String VERSION="15.0.0";',
             '    static final String SOURCE_SHA256="' + source_sha + '";']
    for name, values in groups.items():
        chunks, current = [], ''
        for run in ranges(values):
            if len(current) + len(run) > 100:
                chunks.append(current)
                current = ''
            current += run
        if current:
            chunks.append(current)
        lines.append('    // %d Unicode code points.' % len(values))
        lines.append('    static final String ' + name + '=')
        for index, chunk in enumerate(chunks):
            lines.append('        "' + chunk.replace('\\', '\\\\') + ('";' if index == len(chunks)-1 else '"+'))
    lines += ['    private TrackerUnicode() {}', '}', '']
    target.write_text('\n'.join(lines), encoding='utf-8')
    assert hashlib.sha256(notice.read_bytes()).hexdigest() == license_sha, 'Full Unicode license changed'
    lock_path.write_text(json.dumps({'version': '15.0.0', 'sourceUrl': 'https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt',
        'sourceSha256': source_sha, 'license': 'Unicode-3.0', 'licenseSha256': license_sha,
        'generatedSha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        'codePointCounts': {name: len(values) for name, values in groups.items()}}, indent=2)+'\n')
else:
    lock = json.loads(lock_path.read_text())
    assert hashlib.sha256(target.read_bytes()).hexdigest() == lock['generatedSha256'], 'Frozen Unicode source differs; regenerate from the pinned UCD'
    assert hashlib.sha256(notice.read_bytes()).hexdigest() == lock['licenseSha256'], 'Full Unicode license differs'
    assert lock['sourceSha256'] == source_sha and lock['version'] == '15.0.0', 'Unicode source identity changed'
print('Frozen Unicode 15 tracker character classes and full Unicode license verified.')
